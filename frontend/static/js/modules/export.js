/**
 * Export Manager
 * Handle data export in various formats
 */

export class ExportManager {
  constructor(api) {
    this.api = api;
  }

  async exportJSON(data, filename = 'consistency-report.json') {
    const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
    this.downloadBlob(blob, filename);
  }

  async exportCSV(data, filename = 'consistency-report.csv') {
    if (!data?.length) return;
    
    const headers = Object.keys(data[0]);
    const rows = data.map(row => 
      headers.map(h => {
        const val = row[h];
        // Escape values with commas or quotes
        if (typeof val === 'string' && (val.includes(',') || val.includes('"'))) {
          return `"${val.replace(/"/g, '""')}"`;
        }
        return val;
      }).join(',')
    );

    const csv = [headers.join(','), ...rows].join('\n');
    const blob = new Blob([csv], { type: 'text/csv' });
    this.downloadBlob(blob, filename);
  }

  async exportMarkdown(report, filename = 'consistency-report.md') {
    const md = this.generateMarkdown(report);
    const blob = new Blob([md], { type: 'text/markdown' });
    this.downloadBlob(blob, filename);
  }

  generateMarkdown(report) {
    return `# ConsistenCy Analysis Report

**Repository:** ${report.repo_path || 'Unknown'}  
**Generated:** ${new Date().toISOString()}

## Summary

| Metric | Value |
|--------|-------|
| Average Risk | ${(report.avg_risk || 0).toFixed(3)} |
| Max Risk | ${(report.max_risk || 0).toFixed(3)} |
| Commits Analyzed | ${report.commit_count || 0} |
| High Risk Commits | ${report.high_risk_commits || 0} |

## Top Risky Files

| File | Risk Score | Level |
|------|------------|-------|
${(report.top_risky_files || []).map(f => `| ${f.file} | ${f.avg_risk.toFixed(3)} | ${this.getRiskLevel(f.avg_risk)} |`).join('\n')}

## Security Findings

${(report.security_findings || []).length === 0 ? 'No security issues found.' : 
  (report.security_findings || []).map(f => `- **${f.filepath}**: ${f.evidence}`).join('\n')}

---
*Generated by ConsistenCy*
`;
  }

  downloadBlob(blob, filename) {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }

  getRiskLevel(score) {
    if (score >= 0.75) return '🔴 High';
    if (score >= 0.50) return '🟠 Significant';
    if (score >= 0.25) return '🟡 Minor';
    return '🟢 OK';
  }
}