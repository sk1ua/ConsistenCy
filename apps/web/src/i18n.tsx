function defaultLocale(): Locale {
  if (typeof window === "undefined") return "en-US";
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved === "en-US" || saved === "zh-CN") return saved;
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

function format(template: string, params?: Params): string {
  if (!params) return template;
  return Object.entries(params).reduce((result, [key, value]) => result.replaceAll(`{${key}}`, String(value)), template);
}

const fallback: I18nValue = { locale: "en-US", setLocale: () => undefined, t: (key, params) => format(key, params) };
const I18nContext = createContext<I18nValue>(fallback);

export function I18nProvider({ children, initialLocale }: { children: ReactNode; initialLocale?: Locale }) {
  const [locale, setLocale] = useState<Locale>(() => initialLocale ?? defaultLocale());

  useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem(STORAGE_KEY, locale);
  }, [locale]);

  const t = useCallback((key: string, params?: Params) => format(locale === "zh-CN" ? zh[key] ?? key : key, params), [locale]);
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
